#!/usr/bin/env python3
"""Compile TRECH's deterministic host math to WebAssembly for V8 hosts.

`src/js/DeterministicMath.c` (`trech_dmath`) is the one implementation of the 22
transcendental JavaScript Math functions that the QuickJS host uses. A V8 host reaches the
same results bit for bit only by evaluating that same code without floating-point
contraction. WebAssembly gives exactly that: its f64 add/sub/mul/div/sqrt are single
IEEE-754 operations with no fused multiply-add, on every CPU V8 supports.

This script compiles the C source with Emscripten into a standalone, import-free module and
writes `js/trech_dmath_wasm_data.js` (the module bytes as base64, plus the SHA-256 of the C
source and header it came from). `js/trech_dmath_v8.js` loads that data and installs the
functions as `Math.*`. CTest `trech_dmath_wasm` checks the committed module against the C
golden digests and fails when the C source changes without regenerating it.

Regenerating needs Emscripten (`emcc`) on PATH. Nothing is downloaded.

    python3 scripts/build_dmath_wasm.py [--emcc emcc] [--check]
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import shutil
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "js" / "DeterministicMath.c"
HEADER = ROOT / "include" / "trech" / "js" / "DeterministicMath.h"
OUTPUT = ROOT / "js" / "trech_dmath_wasm_data.js"
UNARY = ("sin", "cos", "tan", "asin", "acos", "atan", "exp", "expm1", "log", "log1p", "log2",
         "log10", "sinh", "cosh", "tanh", "asinh", "acosh", "atanh", "cbrt")
BINARY = ("atan2", "pow", "hypot")
FLAGS = ("-O2", "-ffp-contract=off", "-fno-fast-math", "--no-entry", "-sSTANDALONE_WASM=1",
         "-sERROR_ON_UNDEFINED_SYMBOLS=1")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def dmath_id() -> str:
    for line in HEADER.read_text(encoding="utf-8").splitlines():
        if line.startswith("#define TRECH_DMATH_ID"):
            return line.split('"')[1]
    raise SystemExit("TRECH_DMATH_ID not found in " + str(HEADER))


def emcc_version(emcc: str) -> str:
    out = subprocess.run([emcc, "--version"], capture_output=True, text=True, check=True).stdout
    for line in out.splitlines():
        if line.startswith("emcc"):
            return line.strip()
    return out.splitlines()[0].strip()


def compile_module(emcc: str) -> bytes:
    exports = ",".join("_trech_dmath_" + name for name in UNARY + BINARY)
    with tempfile.TemporaryDirectory(prefix="trech_dmath_wasm_") as work:
        target = Path(work) / "trech_dmath.wasm"
        cmd = [emcc, *FLAGS, "-I" + str(ROOT / "include"), str(SOURCE), "-o", str(target),
               "-sEXPORTED_FUNCTIONS=" + exports]
        proc = subprocess.run(cmd, capture_output=True, text=True)
        if proc.returncode != 0:
            raise SystemExit("emcc failed:\n" + proc.stderr[-4000:])
        return target.read_bytes()


def render(module: bytes, version: str) -> str:
    encoded = base64.b64encode(module).decode("ascii")
    wrapped = "\n".join("  '" + chunk + "' +" for chunk in textwrap.wrap(encoded, 96))
    return f"""// GENERATED by scripts/build_dmath_wasm.py from src/js/DeterministicMath.c. Do not edit.
// TRECH deterministic host math (trech_dmath) as an import-free WebAssembly module, for V8
// hosts. js/trech_dmath_v8.js installs it as Math.*; CTest trech_dmath_wasm checks it.
'use strict';
const TRECH_DMATH_WASM_DATA = Object.freeze({{
  id: '{dmath_id()}',
  sourceSha256: '{sha256(SOURCE)}',
  headerSha256: '{sha256(HEADER)}',
  compiler: '{version}',
  flags: '{" ".join(FLAGS)}',
  unary: {list(UNARY)!r},
  binary: {list(BINARY)!r},
  bytes: {len(module)},
  base64:
{wrapped}
    '',
}});
if (typeof module === 'object' && module && module.exports) module.exports = TRECH_DMATH_WASM_DATA;
else globalThis.TRECH_DMATH_WASM_DATA = TRECH_DMATH_WASM_DATA;
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--emcc", default=shutil.which("emcc"))
    parser.add_argument("--check", action="store_true",
                        help="rebuild and fail if the committed module differs")
    args = parser.parse_args()
    if not args.emcc:
        print("emcc (Emscripten) was not found; set --emcc", file=sys.stderr)
        return 2
    text = render(compile_module(args.emcc), emcc_version(args.emcc))
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; rerun scripts/build_dmath_wasm.py",
                  file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Model catalog: every learned model Studio can find, as Studio shows it (pure: no Qt, no IO).

The Models menu's browser lists the models in the repository (``data/``, ``examples/``,
``projects/``, ``ml/``), the ``trech-ml`` checkpoint store, ``trech arch`` output folders and any
folder the user adds. ``engine/model_catalog.py`` reads the files; this module turns one parsed
file into a :class:`ModelEntry` and builds the views.

Everything shown is read from the file or from a run's recorded ``trech_model_artifacts_v1``
manifest: architecture (layer widths and activations, set-network blocks, or the evolved genome's
readable lines), named inputs and outputs, scale bands, whether the training domain was measured,
the carried holdout, and how the model was generated. The parameter count is the number of
weights and biases stored in the file, or the count the generator recorded for a TorchScript
module. Studio ranks, trains and predicts nothing.

Grouping never invents a system name. Models are grouped by where they came from, by scale band,
by folder, or by their input context: models that read the same set of named inputs share a
context space, which is the unnamed grouping the engine's domain routing works in.
"""
from __future__ import annotations

from dataclasses import dataclass, field
import html
import json
from pathlib import Path, PurePath
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

JSON_SCHEMAS = ("generic_surrogate_v1", "generic_surrogate_v2", "generic_surrogate_v3")
EVOLVED_TWIN_SCHEMA = "trech_evolved_arch_v1"
TORCHSCRIPT_IO_SCHEMA = "trech_torchscript_io_v1"
OUTCOME_SCHEMA = "trech_arch_outcome_v1"
RUN_MANIFEST_SCHEMA = "trech_model_artifacts_v1"

ORIGINS = ("generated", "repository", "store", "folder")
ORIGIN_LABELS = {
    "generated": "Generated by trech arch",
    "repository": "Repository models",
    "store": "Checkpoint store (trech-ml)",
    "folder": "Added folders",
}
GROUP_KEYS = ("origin", "context", "scale", "folder")
GROUP_LABELS = {
    "origin": "Origin",
    "context": "Input context (unnamed)",
    "scale": "Scale band",
    "folder": "Folder",
}
BAND_ORDER = ("atomic", "nano", "micro", "meso", "macro")


@dataclass
class ArchDecision:
    """What a ``trech_arch_outcome_v1`` record says about one model file."""

    job: str
    role: str            # "chosen" | "classic reference" | "evolved, not chosen"
    generator: str       # outcome decision generator ("evolvo" | "classic" | "none")
    reason: str
    ok: bool
    outcome_path: str


@dataclass
class ModelEntry:
    path: Path
    name: str
    origin: str = "folder"
    format: str = "unknown"             # dense | deepsets | mpnn | torchscript
    schema: str = ""
    inputs: List[str] = field(default_factory=list)
    outputs: List[str] = field(default_factory=list)
    scale: str = ""                     # declared `scale` in the file, if any
    trained_bands: List[str] = field(default_factory=list)
    architecture: List[str] = field(default_factory=list)
    parameters: Optional[int] = None
    parameters_source: str = ""         # "stored weights" | "recorded by generator"
    domain: str = "not recorded"
    routing: List[Tuple[str, float, float]] = field(default_factory=list)  # routing_domain ranges
    holdout_r2: Optional[float] = None
    holdout_samples: Optional[int] = None
    generator: str = ""                 # trained_from.generator, when recorded
    provenance: Dict[str, Any] = field(default_factory=dict)
    note: str = ""
    sha256: Optional[str] = None
    size_bytes: Optional[int] = None
    decisions: List[ArchDecision] = field(default_factory=list)
    run_context: Optional[Dict[str, Any]] = None  # matching run manifest entry
    error: str = ""

    @property
    def bands(self) -> List[str]:
        bands = list(self.trained_bands)
        if self.scale and self.scale not in bands:
            bands.insert(0, self.scale)
        return bands

    @property
    def context_key(self) -> Tuple[str, ...]:
        return tuple(sorted(self.inputs))


def is_model_payload(data: Any) -> bool:
    return isinstance(data, dict) and (data.get("model") in JSON_SCHEMAS
                                       or data.get("schema") == EVOLVED_TWIN_SCHEMA)


def _layers_summary(layers: Any) -> Tuple[List[str], int]:
    """Readable widths/activations of a dense stack and its stored weight + bias count."""
    if not isinstance(layers, list):
        return [], 0
    lines, count = [], 0
    for index, layer in enumerate(layers):
        if not isinstance(layer, dict):
            continue
        weights = layer.get("weights") or []
        bias = layer.get("bias") or []
        rows = len(weights) if isinstance(weights, list) else 0
        cols = len(weights[0]) if rows and isinstance(weights[0], list) else 0
        count += rows * cols + (len(bias) if isinstance(bias, list) else 0)
        activation = layer.get("activation") or "none"
        lines.append(f"dense {cols} → {rows}" + ("" if activation == "none" else f", {activation}"))
    return lines, count


def _domain_text(data: Dict[str, Any]) -> str:
    domain = data.get("input_domain")
    if not isinstance(domain, dict):
        return "not measured (engine uses the default 3σ radius)"
    parts = ["measured per-input hull"]
    if isinstance(domain.get("occupancy"), dict):
        parts.append("occupancy bins")
    if isinstance(domain.get("joint"), dict):
        parts.append("joint reference")
    return " + ".join(parts)


def _holdout(data: Dict[str, Any]) -> Tuple[Optional[float], Optional[int]]:
    holdout = data.get("holdout")
    if not isinstance(holdout, dict):
        return None, None
    r2 = holdout.get("r2_min")
    if r2 is None and isinstance(holdout.get("r2"), dict) and holdout["r2"]:
        values = [v for v in holdout["r2"].values() if isinstance(v, (int, float))]
        r2 = min(values) if values else None
    samples = holdout.get("samples", holdout.get("n"))
    return (float(r2) if isinstance(r2, (int, float)) else None,
            int(samples) if isinstance(samples, (int, float)) else None)


def _plain(value: Any) -> str:
    return value if isinstance(value, str) else json.dumps(value, sort_keys=True, default=str)


def _strings(value: Any) -> List[str]:
    return [str(v) for v in value] if isinstance(value, list) else []


def describe_model(data: Dict[str, Any], path: Path, origin: str = "folder") -> ModelEntry:
    """One model file (a generic_surrogate JSON or an evolved TorchScript twin) as an entry."""
    path = Path(path)
    entry = ModelEntry(path=path, name=path.name, origin=origin)
    if not is_model_payload(data):
        entry.error = "not a TRECH model file"
        return entry
    entry.schema = str(data.get("model") or data.get("schema"))
    entry.inputs = _strings(data.get("input_features"))
    entry.outputs = _strings(data.get("output_features"))
    entry.scale = str(data.get("scale") or "")
    entry.trained_bands = _strings(data.get("trained_scale_bands"))
    entry.domain = _domain_text(data)
    routing = data.get("routing_domain")
    if isinstance(routing, dict):
        names, lows, highs = routing.get("features"), routing.get("min"), routing.get("max")
        if isinstance(names, list) and isinstance(lows, list) and isinstance(highs, list):
            entry.routing = [(str(n), float(lo), float(hi)) for n, lo, hi in zip(names, lows, highs)
                             if isinstance(lo, (int, float)) and isinstance(hi, (int, float))]
    entry.holdout_r2, entry.holdout_samples = _holdout(data)
    note = data.get("note")
    if isinstance(note, str):
        entry.note = note
    elif isinstance(note, dict):
        entry.note = "\n".join(f"{key}: {_plain(value)}" for key, value in note.items())
    trained = data.get("trained_from") if isinstance(data.get("trained_from"), dict) else {}
    entry.generator = str(trained.get("generator") or "")
    for key in ("generator", "structure", "seed", "selection_loss", "stop_reason", "epochs",
                "train", "selection", "test", "request_sha256", "classic_reference"):
        if key in trained:
            entry.provenance[key] = trained[key]

    if entry.schema == EVOLVED_TWIN_SCHEMA:
        entry.format = "torchscript"
        entry.name = path.name[: -len(".arch.json")] + ".pt" if path.name.endswith(".arch.json") else path.name
        entry.architecture = _strings(trained.get("architecture"))
        if isinstance(trained.get("parameter_count"), int):
            entry.parameters = trained["parameter_count"]
            entry.parameters_source = "recorded by generator"
        return entry

    if entry.schema == "generic_surrogate_v3":
        network = data.get("network") if isinstance(data.get("network"), dict) else data
        kind = str(network.get("kind") or "set")
        entry.format = kind
        total = 0
        for block in ("phi", "message", "update", "rho"):
            lines, count = _layers_summary(network.get(block))
            if lines:
                entry.architecture.append(f"{block}: " + "; ".join(lines))
                total += count
        entry.parameters, entry.parameters_source = total, "stored weights"
        return entry

    entry.format = "dense"
    network = data.get("network") if isinstance(data.get("network"), dict) else {}
    lines, count = _layers_summary(data.get("layers") if "layers" in data else network.get("layers"))
    entry.architecture = lines
    entry.parameters, entry.parameters_source = count, "stored weights"
    if not lines and isinstance(trained.get("architecture"), list):
        entry.architecture = _strings(trained["architecture"])
    return entry


def outcome_decisions(outcome: Dict[str, Any], outcome_path: Path) -> Dict[str, ArchDecision]:
    """Map each model path an outcome names to what the engine decided about it."""
    if not isinstance(outcome, dict) or outcome.get("schema") != OUTCOME_SCHEMA:
        return {}
    decision = outcome.get("decision") if isinstance(outcome.get("decision"), dict) else {}
    chosen = str(decision.get("model") or "")
    job = str(outcome.get("name") or Path(outcome_path).name)
    common = dict(job=job, generator=str(decision.get("generator") or ""),
                  reason=str(decision.get("reason") or ""), ok=decision.get("ok") is True,
                  outcome_path=str(outcome_path))
    out: Dict[str, ArchDecision] = {}
    classic = outcome.get("classic") if isinstance(outcome.get("classic"), dict) else {}
    evolvo = outcome.get("evolvo") if isinstance(outcome.get("evolvo"), dict) else {}
    for model, role in ((classic.get("model"), "classic reference"), (evolvo.get("model"), "evolved, not chosen")):
        if model:
            out[str(model)] = ArchDecision(role="chosen" if str(model) == chosen else role, **common)
    if chosen and chosen not in out:
        out[chosen] = ArchDecision(role="chosen", **common)
    return out


def attach_run(entries: Iterable[ModelEntry], manifest: Optional[Dict[str, Any]]) -> int:
    """Mark entries a loaded run used (same SHA-256 as its recorded snapshot). Returns matches."""
    for entry in entries:
        entry.run_context = None
    if not isinstance(manifest, dict) or manifest.get("schema") != RUN_MANIFEST_SCHEMA:
        return 0
    by_sha: Dict[str, Dict[str, Any]] = {}
    for model in manifest.get("models") or []:
        if isinstance(model, dict) and model.get("loaded") is True and model.get("sha256"):
            by_sha.setdefault(str(model["sha256"]), model)
    matches = 0
    for entry in entries:
        if entry.sha256 and entry.sha256 in by_sha:
            entry.run_context = by_sha[entry.sha256]
            matches += 1
    return matches


def _band_rank(band: str) -> int:
    return BAND_ORDER.index(band) if band in BAND_ORDER else len(BAND_ORDER)


def group_label(entry: ModelEntry, key: str, root: Optional[Path] = None) -> str:
    if key == "origin":
        return ORIGIN_LABELS.get(entry.origin, entry.origin)
    if key == "scale":
        return entry.bands[0] if entry.bands else "no scale recorded"
    if key == "folder":
        parent = entry.path.parent
        if root is not None:
            try:
                parent = parent.relative_to(root)
            except ValueError:
                pass
        return str(PurePath(parent).as_posix()) or "."
    if key == "context":
        return "inputs: " + (", ".join(entry.context_key) if entry.inputs else "none recorded")
    raise ValueError(f"unknown group key {key!r}")


def group_entries(entries: Sequence[ModelEntry], key: str,
                  root: Optional[Path] = None) -> List[Tuple[str, List[ModelEntry]]]:
    groups: Dict[str, List[ModelEntry]] = {}
    for entry in entries:
        groups.setdefault(group_label(entry, key, root), []).append(entry)
    for members in groups.values():
        members.sort(key=lambda e: (e.name.lower(), str(e.path)))
    if key == "origin":
        order = {ORIGIN_LABELS[o]: i for i, o in enumerate(ORIGINS)}
        labels = sorted(groups, key=lambda label: (order.get(label, len(order)), label))
    elif key == "scale":
        labels = sorted(groups, key=lambda label: (_band_rank(label), label))
    elif key == "context":
        # Shared context spaces first: those are the groups routing can split.
        labels = sorted(groups, key=lambda label: (-len(groups[label]), label))
    else:
        labels = sorted(groups)
    return [(label, groups[label]) for label in labels]


def matches_filter(entry: ModelEntry, text: str) -> bool:
    text = text.strip().lower()
    if not text:
        return True
    haystack = " ".join([entry.name, str(entry.path), entry.format, entry.generator, " ".join(entry.bands),
                         " ".join(entry.inputs), " ".join(entry.outputs)]).lower()
    return all(token in haystack for token in text.split())


def parameters_text(entry: ModelEntry) -> str:
    return "–" if entry.parameters is None else f"{entry.parameters:,}"


def _row(label: str, value: str) -> str:
    return f"<tr><th align='left' valign='top'>{html.escape(label)}</th><td>{value}</td></tr>"


def entry_html(entry: ModelEntry, root: Optional[Path] = None) -> str:
    """Details pane. Every value is escaped and comes from the file or the run manifest."""
    esc = html.escape
    path = entry.path
    if root is not None:
        try:
            path = entry.path.relative_to(root)
        except ValueError:
            pass
    rows = [_row("File", esc(str(path))), _row("Origin", esc(ORIGIN_LABELS.get(entry.origin, entry.origin)))]
    if entry.error:
        rows.append(_row("Problem", esc(entry.error)))
        return f"<h3>{esc(entry.name)}</h3><table cellspacing='4'>{''.join(rows)}</table>"
    rows.append(_row("Format", esc(f"{entry.format} ({entry.schema})")))
    params = parameters_text(entry)
    if entry.parameters_source:
        params += f" <i>({esc(entry.parameters_source)})</i>"
    rows.append(_row("Parameters", params))
    rows.append(_row("Inputs", esc(", ".join(entry.inputs) or "none recorded")))
    rows.append(_row("Outputs", esc(", ".join(entry.outputs) or "none recorded")))
    rows.append(_row("Scale", esc(", ".join(entry.bands) or "none recorded")))
    rows.append(_row("Training domain", esc(entry.domain)))
    if entry.routing:
        ranges = "; ".join(f"{name} {lo:.4g} … {hi:.4g}" for name, lo, hi in entry.routing)
        rows.append(_row("Routing domain", esc(ranges) + " <i>(measured; used only to route elements)</i>"))
    if entry.holdout_r2 is not None:
        held = f"worst-output R² {entry.holdout_r2:.4f}"
        if entry.holdout_samples is not None:
            held += f" on {entry.holdout_samples} held-out rows"
        rows.append(_row("Holdout", esc(held)))
    else:
        rows.append(_row("Holdout", "<i>no carried accuracy</i>"))
    if entry.generator:
        rows.append(_row("Generator", esc(entry.generator)))
    for key, value in entry.provenance.items():
        if key == "generator":
            continue
        rows.append(_row(key.replace("_", " "), esc(_plain(value))))
    if entry.sha256:
        rows.append(_row("SHA-256", f"<code>{esc(entry.sha256)}</code>"))
    body = f"<h3>{esc(entry.name)}</h3><table cellspacing='4'>{''.join(rows)}</table>"
    if entry.architecture:
        body += "<h4>Architecture</h4><pre>" + esc("\n".join(entry.architecture)) + "</pre>"
    for decision in entry.decisions:
        verdict = "ok" if decision.ok else "failed"
        body += ("<h4>trech arch</h4><p>" + esc(f"Job {decision.job}: {decision.role}. "
                 f"Decision {verdict}, generator {decision.generator or 'none'}: {decision.reason}") +
                 "<br><small>" + esc(decision.outcome_path) + "</small></p>")
    if entry.run_context is not None:
        ctx = entry.run_context
        parts = [f"registered as {ctx.get('name') or 'unnamed'}"]
        for key in ("scale", "operator_role", "element_kind"):
            if ctx.get(key):
                parts.append(f"{key.replace('_', ' ')}: {ctx[key]}")
        keys = ctx.get("required_context_keys")
        if isinstance(keys, list) and keys:
            parts.append("required context: " + ", ".join(str(k) for k in keys))
        body += "<h4>Used by the loaded run</h4><p>" + esc("; ".join(parts)) + "</p>"
    if entry.note:
        body += "<h4>Note</h4><pre>" + esc(entry.note) + "</pre>"
    return body
